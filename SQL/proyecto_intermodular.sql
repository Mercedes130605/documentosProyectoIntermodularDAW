
CREATE DATABASE IF NOT EXISTS proyecto_intermodular;
USE proyecto_intermodular;

DROP TABLE IF EXISTS REPARTO_PEDIDO;
DROP TABLE IF EXISTS DETALLE_PEDIDO;
DROP TABLE IF EXISTS PRODUCTO;
DROP TABLE IF EXISTS REPARTO;
DROP TABLE IF EXISTS PEDIDO;
DROP TABLE IF EXISTS CATEGORIA;
DROP TABLE IF EXISTS TRABAJADOR;
DROP TABLE IF EXISTS CLIENTE;

-- TABLA CLIENTE
CREATE TABLE CLIENTE (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    telefono VARCHAR(15) NOT NULL
);

-- TABLA TRABAJADOR
CREATE TABLE TRABAJADOR (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    telefono VARCHAR(15) NOT NULL,
    rol ENUM('ADMINISTRADOR', 'OFICINISTA', 'CAMIONERO') NOT NULL
) ;

-- TABLA CATEGORIA
CREATE TABLE CATEGORIA (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL UNIQUE
);

-- TABLA PEDIDO
CREATE TABLE PEDIDO (
    id INT AUTO_INCREMENT PRIMARY KEY,
    fecha DATE NOT NULL,
    id_cliente INT NOT NULL,
    id_trabajador INT NOT NULL,
    CONSTRAINT fk_pedido_cliente
        FOREIGN KEY (id_cliente) REFERENCES CLIENTE(id),
    CONSTRAINT fk_pedido_trabajador
        FOREIGN KEY (id_trabajador) REFERENCES TRABAJADOR(id)
);

-- TABLA REPARTO
CREATE TABLE REPARTO (
    id INT AUTO_INCREMENT PRIMARY KEY,
    fecha DATE NOT NULL,
    id_trabajador INT NOT NULL,
    CONSTRAINT fk_reparto_trabajador
        FOREIGN KEY (id_trabajador) REFERENCES TRABAJADOR(id)
);

-- TABLA PRODUCTO
CREATE TABLE PRODUCTO (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    precio DECIMAL(10,2) NOT NULL,
    stock INT NOT NULL,
    id_categoria INT NOT NULL,
    CONSTRAINT chk_producto_precio
        CHECK (precio >= 0),
    CONSTRAINT chk_producto_stock
        CHECK (stock >= 0),
    CONSTRAINT fk_producto_categoria
        FOREIGN KEY (id_categoria) REFERENCES CATEGORIA(id)
);

-- TABLA DETALLE_PEDIDO
CREATE TABLE DETALLE_PEDIDO (
    id INT AUTO_INCREMENT PRIMARY KEY,
    precio DECIMAL(10,2) NOT NULL,
    id_pedido INT NOT NULL,
    id_producto INT NOT NULL,
    CONSTRAINT chk_detalle_precio
        CHECK (precio >= 0),
    CONSTRAINT fk_detalle_pedido
        FOREIGN KEY (id_pedido) REFERENCES PEDIDO(id),
    CONSTRAINT fk_detalle_producto
        FOREIGN KEY (id_producto) REFERENCES PRODUCTO(id)
);

-- TABLA INTERMEDIA PARA RELACIONAR REPARTOS Y PEDIDOS
CREATE TABLE REPARTO_PEDIDO (
    id_reparto INT NOT NULL,
    id_pedido INT NOT NULL,
    PRIMARY KEY (id_reparto, id_pedido),
    CONSTRAINT uq_reparto_pedido
        UNIQUE (id_pedido),
    CONSTRAINT fk_reparto_pedido_reparto
        FOREIGN KEY (id_reparto) REFERENCES REPARTO(id),
    CONSTRAINT fk_reparto_pedido_pedido
        FOREIGN KEY (id_pedido) REFERENCES PEDIDO(id)
);
